/// Prints an error and its causes to stderr (used by `fun main() throws`).
pub fn report<E: Into<AnyError>>(err: E) {
    let err: AnyError = err.into();
    eprintln!("error: {}", err);
    let mut source = err.source();
    while let Some(s) = source {
        eprintln!("  caused by: {}", s);
        source = s.source();
    }
}
